// повідомлень (напр. тости notify()) це JS-конкатенація зі вставленими
// даними («⚠️ Пісню «Ім'я» не знайдено»), і в DOM опиняються ОДНИМ текстовим
// вузлом. Підрядкова заміна дозволяє перекласти статичну частину, лишивши
// вставлені дані (назву пісні, IP тощо) незайманими.
function uiTranslateText(raw, lang) {
  if (!raw) return raw;
  var keys = uiDictKeysSorted();
  var out = raw;
  for (var i = 0; i < keys.length; i++) {
    if (out.indexOf(keys[i]) === -1) continue;
    var tr = UI_DICT[keys[i]][lang];
    if (!tr) continue;
    out = out.split(keys[i]).join(tr);
  }
  return out;
}

// Пропускаємо текстові вузли всередині <script>/<style> — інакше на
// document.body (uiTranslateAll) обхід зайшов би й у вбудований <script>
// з тисячами рядків JS прямо в index.html, намагаючись підмінити підрядки
// в сирому коді. Функціонально нешкідливо (скрипт уже виконався, зміна
// тексту його не перезапускає), але марно й повільно на кожну зміну мови —
// знайдено саме цим прогоном перевірки на баги.
// Також пропускаємо все всередині [data-no-translate] — контейнери з
// ЖИВИМ вмістом (текст вірша Біблії/пісні, прев'ю того, що зараз в ефірі),
// а не авторський текст інтерфейсу. Підрядкова заміна там небезпечна: цей
// текст потім читається назад (sendBibleToProjector, broadcastRemoteState,
// getCurrentContent) і йде в ефір/бюлетень уже спотвореним. Знайдено рев'ю
// коду цього ж проходу.
function _uiSkipScriptStyle(node) {
  var p = node.parentElement;
  if (p && (p.tagName === 'SCRIPT' || p.tagName === 'STYLE')) return NodeFilter.FILTER_REJECT;
  if (p && p.closest && p.closest('[data-no-translate]')) return NodeFilter.FILTER_REJECT;
  return NodeFilter.FILTER_ACCEPT;
}
function uiTranslateNode(root) {
  if (!root) return;
  var lang = uiCurrentLang();
  if (lang === 'ua') return;

  var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode: _uiSkipScriptStyle });
  var toProcess = [];
  var node;
  while ((node = walker.nextNode())) toProcess.push(node);
  toProcess.forEach(function(n) {
    if (!n.nodeValue || !n.nodeValue.trim()) return;
    var translated = uiTranslateText(n.nodeValue, lang);
    if (translated !== n.nodeValue) n.nodeValue = translated;
  });

  var attrs = ['placeholder', 'title', 'aria-label'];
  var withAttrs = root.querySelectorAll('[placeholder],[title],[aria-label]');
  for (var i = 0; i < withAttrs.length; i++) {
    var el = withAttrs[i];
    if (el.closest && el.closest('[data-no-translate]')) continue;
    for (var j = 0; j < attrs.length; j++) {
      var a = attrs[j];
      var v = el.getAttribute(a);
      if (!v) continue;
      var tv = uiTranslateText(v, lang);
      if (tv !== v) el.setAttribute(a, tv);
    }
  }
}

// Перекладає геть усе, що зараз в DOM (весь body) — викликається при зміні
// мови й при повній перезбірці меню, щоб охопити і вже відмальовані раніше
// вкладки (одноразовий рендер через pv2Init), і статичну шапку/діалоги.
function uiTranslateAll() {
  uiTranslateNode(document.body);
}

// Перекладає конкретну вкладку за id (викликається з showTab при кожному
// перемиканні) — дешевше, ніж перекладати весь document.body щоразу.
function uiTranslateActiveTabByName(name) {
  var el = document.getElementById('tab-content-' + name);
  if (el) uiTranslateNode(el);
}
